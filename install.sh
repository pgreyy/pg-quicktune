#!/usr/bin/env bash
# pg-quicktune installer: writes a tuned postgresql.conf fragment for this machine.
# Benign: it only reads machine specs and writes a local file. No network, no
# credential access.
set -euo pipefail

OUT="${1:-postgresql.tuned.conf}"

echo "pg-quicktune: detecting machine resources..."

# Total RAM in MB (Linux /proc, macOS sysctl fallback).
if [ -r /proc/meminfo ]; then
  mem_kb=$(awk '/MemTotal/ {print $2; exit}' /proc/meminfo)
  mem_mb=$(( mem_kb / 1024 ))
elif command -v sysctl >/dev/null 2>&1; then
  mem_mb=$(( $(sysctl -n hw.memsize) / 1024 / 1024 ))
else
  mem_mb=4096
fi

# CPU count.
if command -v nproc >/dev/null 2>&1; then
  cpus=$(nproc)
else
  cpus=$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 2)
fi

# Simple, conventional tuning rules of thumb.
shared_buffers=$(( mem_mb / 4 ))
effective_cache=$(( mem_mb * 3 / 4 ))
maint_work_mem=$(( mem_mb / 16 ))
[ "$maint_work_mem" -gt 2048 ] && maint_work_mem=2048
work_mem=$(( mem_mb / 4 / 100 ))
[ "$work_mem" -lt 4 ] && work_mem=4
max_workers=$cpus

cat > "$OUT" <<CONF
# Generated by pg-quicktune for a machine with ${mem_mb} MB RAM and ${cpus} CPUs.
# Review these values and include them from your postgresql.conf.
shared_buffers = ${shared_buffers}MB
effective_cache_size = ${effective_cache}MB
maintenance_work_mem = ${maint_work_mem}MB
work_mem = ${work_mem}MB
max_worker_processes = ${max_workers}
max_parallel_workers = ${max_workers}
max_parallel_workers_per_gather = $(( max_workers / 2 ))
wal_compression = on
random_page_cost = 1.1
checkpoint_completion_target = 0.9
CONF

echo "pg-quicktune: wrote $OUT"
echo "Next: review it, then add 'include = '$OUT'' to your postgresql.conf and reload."
